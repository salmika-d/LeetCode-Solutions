class Solution(object):
    def addBinary(self, a, b):
        i=len(a)-1
        j=len(b)-1
        c=0
        temp=0
        res=""
        while(i!=-1 and j!=-1):
            n=int(a[i])+int(b[j])+c
            if(n==2):
                res="0"+res
                c=1
            elif(n==3):
                res="1"+res
                c=1
            else:
                res=str(n)+res
                c=0
            i-=1
            j-=1
        while(i!=-1):
            if(c!=0):
                temp=int(a[i])+c
                if(temp==2):
                   res="0"+res
                   c=1
                elif(temp==3):
                   res="1"+res
                   c=1
                else:
                   res=str(temp)+res
                   c=0
            else:
               res=a[i]+res
            i-=1
        while(j!=-1):
            if(c!=0):
                temp=int(b[j])+c
                if(temp==2):
                   res="0"+res
                   c=1
                elif(temp==3):
                   res="1"+res
                   c=1
                else:
                   res=str(temp)+res
                   c=0
            else:
               res=b[j]+res
            j-=1
        if(c==1):
            res="1"+res
        return res       